<#
.SYNOPSIS
    Export the default Outlook calendar to an Org file.

.DESCRIPTION
    Reads appointments from the running (classic) Outlook through COM and
    writes them as Org entries with active timestamps, so org-agenda shows
    them.  Recurring meetings are expanded into individual occurrences.
    Declined and cancelled meetings are skipped.

    Outlook is not started if it isn't already running; the script exits
    with code 2 and the existing Org file is left alone.

.EXAMPLE
    powershell -NoProfile -File outlook-calendar.ps1 -OutFile C:\org\outlook.org
#>
param(
    [Parameter(Mandatory = $true)][string]$OutFile,
    [int]$DaysBack = 7,
    [int]$DaysAhead = 21
)

$ErrorActionPreference = 'Stop'
$inv = [Globalization.CultureInfo]::InvariantCulture

try {
    $outlook = [Runtime.InteropServices.Marshal]::GetActiveObject('Outlook.Application')
} catch {
    [Console]::Error.WriteLine('Outlook is not running; calendar not exported.')
    exit 2
}

function Format-OrgStamp([datetime]$d, [bool]$withTime) {
    if ($withTime) { $d.ToString('yyyy-MM-dd ddd HH:mm', $inv) }
    else { $d.ToString('yyyy-MM-dd ddd', $inv) }
}

function Get-OrgTimestamp($item) {
    $start = [datetime]$item.Start
    $end = [datetime]$item.End
    if ($item.AllDayEvent) {
        # Outlook's all-day end is exclusive (midnight after the last day).
        $last = $end.AddDays(-1)
        if ($last.Date -le $start.Date) { return "<$(Format-OrgStamp $start $false)>" }
        return "<$(Format-OrgStamp $start $false)>--<$(Format-OrgStamp $last $false)>"
    }
    if ($start.Date -eq $end.Date) {
        return "<$(Format-OrgStamp $start $true)-$($end.ToString('HH:mm', $inv))>"
    }
    return "<$(Format-OrgStamp $start $true)>--<$(Format-OrgStamp $end $true)>"
}

function Clean([string]$s) {
    if ($null -eq $s) { return '' }
    ($s -replace '[\r\n]+', ' ').Trim()
}

# OlResponseStatus / OlMeetingStatus values
$responseNames = @{ 0 = 'None'; 1 = 'Organizer'; 2 = 'Tentative'; 3 = 'Accepted'; 4 = 'Declined'; 5 = 'Not responded' }
$olResponseDeclined = 4
$olMeetingCanceled = 5
$olMeetingReceivedAndCanceled = 7

$rangeStart = (Get-Date).Date.AddDays(-$DaysBack)
$rangeEnd = (Get-Date).Date.AddDays($DaysAhead + 1)

$calendar = $outlook.GetNamespace('MAPI').GetDefaultFolder(9)   # olFolderCalendar
$items = $calendar.Items
$items.Sort('[Start]')
$items.IncludeRecurrences = $true
# Restrict wants dates in the current locale's short format, without seconds.
$filter = "[Start] < '$($rangeEnd.ToString('g'))' AND [End] > '$($rangeStart.ToString('g'))'"
$found = $items.Restrict($filter)

$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('#+title: Outlook Calendar')
[void]$sb.AppendLine('#+startup: overview')
[void]$sb.AppendLine("# Generated by outlook-calendar.ps1 at $((Get-Date).ToString('yyyy-MM-dd HH:mm', $inv)); edits are overwritten.")
[void]$sb.AppendLine('')

# Iterate with GetFirst/GetNext: Count is meaningless with IncludeRecurrences.
$item = $found.GetFirst()
while ($null -ne $item) {
    $status = [int]$item.MeetingStatus
    $response = [int]$item.ResponseStatus
    $skip = ($response -eq $olResponseDeclined) -or
            ($status -eq $olMeetingCanceled) -or
            ($status -eq $olMeetingReceivedAndCanceled)

    if (-not $skip) {
        $subject = Clean $item.Subject
        if ($subject -eq '') { $subject = '(no subject)' }
        $tags = if ($response -eq 2) { ' :tentative:' } else { '' }
        [void]$sb.AppendLine("* $subject$tags")
        [void]$sb.AppendLine(':PROPERTIES:')
        $location = Clean $item.Location
        if ($location) { [void]$sb.AppendLine(":LOCATION: $location") }
        $organizer = Clean $item.Organizer
        if ($organizer) { [void]$sb.AppendLine(":ORGANIZER: $organizer") }
        $responseName = $responseNames[$response]
        if ($responseName) { [void]$sb.AppendLine(":RESPONSE: $responseName") }
        # Attendees by OlMeetingRecipientType.  Names only: reading
        # addresses can set off Outlook's security prompt.  The organizer
        # is already in ORGANIZER.
        $attendees = @{ 1 = @(); 2 = @(); 3 = @() }
        foreach ($r in $item.Recipients) {
            $name = Clean $r.Name
            $type = [int]$r.Type
            if ($name -and $name -ne $organizer -and $attendees.ContainsKey($type)) {
                $attendees[$type] += $name
            }
        }
        foreach ($t in @(@(1, 'REQUIRED'), @(2, 'OPTIONAL'), @(3, 'RESOURCES'))) {
            $names = $attendees[$t[0]]
            if ($names.Count) { [void]$sb.AppendLine(":$($t[1]): $($names -join '; ')") }
        }
        [void]$sb.AppendLine(':END:')
        [void]$sb.AppendLine((Get-OrgTimestamp $item))

        $join = [regex]::Match([string]$item.Body, 'https://teams\.microsoft\.com/l/meetup-join/[^\s<>"]+')
        if ($join.Success) { [void]$sb.AppendLine("[[$($join.Value)][Join Teams meeting]]") }
        elseif ($location -match '^https?://\S+$') { [void]$sb.AppendLine("[[$location][Join meeting]]") }
        [void]$sb.AppendLine('')
    }
    $item = $found.GetNext()
}

# Write to a temp file and swap it in, so Emacs never reads a half-written file.
$utf8 = New-Object Text.UTF8Encoding $false
$tmp = "$OutFile.tmp"
[IO.File]::WriteAllText($tmp, $sb.ToString(), $utf8)
Move-Item -LiteralPath $tmp -Destination $OutFile -Force
